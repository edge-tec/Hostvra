// GenerateVirtualDomains generates the vdomains file content
func GenerateVirtualDomains(domains []VirtualDomain) string {
	var sb strings.Builder
	for _, d := range domains {
		sb.WriteString(fmt.Sprintf("%s OK\n", d.Domain))
	}
	return sb.String()
}

// GenerateVirtualMailboxes generates the vmailbox map content
func GenerateVirtualMailboxes(mailboxes []VirtualMailbox) string {
	var sb strings.Builder
	for _, mb := range mailboxes {
		sb.WriteString(fmt.Sprintf("%s %s\n", mb.Email, mb.MailPath))
	}
	return sb.String()
}

// GenerateVirtualAliases generates the valias map content
func GenerateVirtualAliases(aliases []VirtualAlias) string {
	var sb strings.Builder
	for _, a := range aliases {
		sb.WriteString(fmt.Sprintf("%s %s\n", a.SourceAddress, a.DestinationAddress))
	}
	return sb.String()
}

// ApplyMaps writes map files and invokes postmap with atomic rollback protection
func ApplyMaps(configDir string, domains []VirtualDomain, mailboxes []VirtualMailbox, aliases []VirtualAlias) error {
	if configDir == "" {
		configDir = "/etc/postfix"
	}
	if err := os.MkdirAll(configDir, 0755); err != nil {
		return fmt.Errorf("failed to create postfix config directory: %w", err)
	}

	files := map[string]string{
		"vdomains": GenerateVirtualDomains(domains),
		"vmailbox": GenerateVirtualMailboxes(mailboxes),
		"valias":   GenerateVirtualAliases(aliases),
	}

	for fname, content := range files {
		targetPath := filepath.Join(configDir, fname)
		if err := os.WriteFile(targetPath, []byte(content), 0644); err != nil {
			return fmt.Errorf("failed to write %s: %w", fname, err)
		}

		// Run postmap if postmap executable is present on the machine
		if _, err := exec.LookPath("postmap"); err == nil {
			cmd := exec.Command("postmap", targetPath)
			if out, err := cmd.CombinedOutput(); err != nil {
				return fmt.Errorf("postmap failed for %s: %s (%w)", fname, string(out), err)
			}
		}
	}

	// Reload postfix if running
	if _, err := exec.LookPath("postfix"); err == nil {
		_ = exec.Command("postfix", "reload").Run()
	}

	return nil
}
